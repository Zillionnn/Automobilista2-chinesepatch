def translate_entry(table, key, english):
    """Translate an entry, returning Chinese text or None to skip."""
    # Skip UNTRANSLATED placeholders - keep as-is
    if english.startswith("UNTRANSLATED ("):
        return english

    # Direct lookup in glossary
    if english in RACING_TERMS:
        return RACING_TERMS[english]

    # Tyre compound types
    if english in TYRE_TYPES:
        return TYRE_TYPES[english]

    # Sentence translations
    if english in SENTENCE_TRANSLATIONS:
        return SENTENCE_TRANSLATIONS[english]

    # Fuzzy match for long sentences (first 60 chars match, normalized quotes)
    if len(english) > 60:
        def normalize(s):
            return s.replace("\u201c", '"').replace("\u201d", '"').replace("\u2018", "'").replace("\u2019", "'")
        prefix = normalize(english[:60])
        for en_key, zh_val in SENTENCE_TRANSLATIONS.items():
            if normalize(en_key[:60]) == prefix:
                return zh_val

    # Track names (General_TrackDetails) - keep as-is (proper nouns)
    if table == "General" and key.startswith("General_TrackDetails_"):
        return english

    # Controller preset brand names - keep as-is
    if "ControllerPresets" in key:
        if english in ("Default", "New Default", "Default+"):
            return {"Default": "默认", "New Default": "新默认", "Default+": "默认+"}.get(english)
        if english in ("Look Up", "Look Down"):
            return {"Look Up": "向上看", "Look Down": "向下看"}.get(english)
        if english == "Direct Drive Generic":
            return "直驱通用"
        if english == "Custom DD Wheel":
            return "自定义直驱方向盘"
        if "custom setup" in english.lower():
            return english.split(" custom setup")[0] + " 自定义设置"
        # Brand names: keep as-is
        return english

    # Handle compound patterns
    # "GEAR N" pattern
    if english.startswith("GEAR ") and english[5:].isdigit():
        return english[5:] + "档"

    # Tyre compound patterns with brand names
    if key.startswith("Game_Tyre_"):
        # Already handled by TYRE_TYPES, but check for brand-prefixed types
        for ttype_en, ttype_zh in TYRE_TYPES.items():
            if english == ttype_en:
                return ttype_zh
        # Brand + type patterns (e.g., "Avon ZZR")
        if any(brand in english for brand in ["Avon", "Pirelli", "Michelin", "Goodyear", "Dunlop", "Hankook"]):
            return english  # Keep brand tyre names as-is
        return english  # Fallback: keep as-is

    # "On"/"Off" short forms
    if english == "On":
        return "开"
    if english == "Off":
        return "关"

    return None  # No translation found


def main():
    untr = json.load(open(r"F:\Game\AMS2-ZH\work\translations\untranslated.json", encoding="utf-8"))

    translations = {}
    translated = 0
    skipped = 0
    no_translation = []

    for e in untr:
        table = e["table"]
        key = e["key"]
        english = e["english"]

        zh = translate_entry(table, key, english)
        if zh and zh != english:
            if table not in translations:
                translations[table] = {}
            translations[table][key] = zh
            translated += 1
        elif zh == english:
            # Kept as-is (track names, brand names, placeholders)
            if table not in translations:
                translations[table] = {}
            translations[table][key] = zh
            skipped += 1
        else:
            no_translation.append(e)

    # Write translations.json
    out_path = r"F:\Game\AMS2-ZH\work\translations\translations.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(translations, f, ensure_ascii=False, indent=2)

    print("Translated: %d" % translated)
    print("Kept as-is: %d" % skipped)
    print("No translation: %d" % len(no_translation))
    print("Output: %s" % out_path)

    if no_translation:
        print("\nMissing translations:")
        from collections import Counter
        c = Counter(e["table"] for e in no_translation)
        for t, n in c.most_common():
            print("  %s: %d" % (t, n))
        # Write missing list
        with open(r"F:\Game\AMS2-ZH\work\translations\missing.json", "w", encoding="utf-8") as f:
            json.dump(no_translation, f, ensure_ascii=False, indent=2)
        print("Missing list: work/translations/missing.json")


if __name__ == "__main__":
    main()
